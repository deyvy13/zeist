// Generates lib/post-locales.generated.ts — a plain data map of each blog post's
// slug in every locale that publishes it, keyed by its translation key (the
// Spanish slug). Posts carry their own slug per language (oct-2026), so the
// language switcher, hreflang, the sitemap and next.config's redirects need
// this map, and the switcher is a client component that cannot read the
// filesystem: the map is baked into source before the build.
//
// Run via the `prebuild` / `predev` npm scripts; also safe to run by hand.
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const LOCALES = ["es", "pt", "en"];
const BLOG_DIR = path.join(process.cwd(), "content", "blog");
const OUT = path.join(process.cwd(), "lib", "post-locales.generated.ts");

const routes = {};
const seen = new Map();
for (const locale of LOCALES) {
  const dir = path.join(BLOG_DIR, locale);
  if (!fs.existsSync(dir)) continue;
  for (const file of fs.readdirSync(dir).sort()) {
    if (!file.endsWith(".mdx")) continue;
    const slug = file.replace(/\.mdx$/, "");
    const { data } = matter(fs.readFileSync(path.join(dir, file), "utf8"));
    if (data.draft) continue; // archived posts are not "available"
    const key = data.translationKey ? String(data.translationKey) : slug;
    if (routes[key]?.[locale]) throw new Error(`Two ${locale} posts share translationKey "${key}"`);
    // A slug must point at one post only, or old-URL redirects would be ambiguous.
    const owner = seen.get(`${locale}:${slug}`);
    if (owner) throw new Error(`Slug "${slug}" repeats in ${locale}`);
    seen.set(`${locale}:${slug}`, key);
    (routes[key] ??= {})[locale] = slug;
  }
}

const body = `// AUTO-GENERATED by scripts/gen-post-locales.mjs — do not edit by hand.
// Slug of each blog post in every locale that publishes it, keyed by its
// translation key (the Spanish slug). Read by lib/routes.ts (public URLs,
// hreflang, the language switcher) and next.config.ts (old-URL redirects).
import type { Locale } from "./i18n";

export const postRoutes: Readonly<Record<string, Partial<Record<Locale, string>>>> = ${JSON.stringify(
  routes,
  null,
  2,
)};
`;

fs.writeFileSync(OUT, body, "utf8");
console.log(`post-locales: ${Object.keys(routes).length} posts written`);
