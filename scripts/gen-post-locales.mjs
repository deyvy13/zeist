// Generates lib/post-locales.generated.ts — a plain data map of which locales
// publish each blog slug. The language switcher is a client component and
// cannot read the filesystem, so this is baked into source before the build.
//
// Run via the `prebuild` / `predev` npm scripts; also safe to run by hand.
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const LOCALES = ["es", "pt", "en"];
const BLOG_DIR = path.join(process.cwd(), "content", "blog");
const OUT = path.join(process.cwd(), "lib", "post-locales.generated.ts");

const bySlug = {};
for (const locale of LOCALES) {
  const dir = path.join(BLOG_DIR, locale);
  if (!fs.existsSync(dir)) continue;
  for (const file of fs.readdirSync(dir)) {
    if (!file.endsWith(".mdx")) continue;
    const slug = file.replace(/\.mdx$/, "");
    const { data } = matter(fs.readFileSync(path.join(dir, file), "utf8"));
    if (data.draft) continue; // archived posts are not "available"
    (bySlug[slug] ??= []).push(locale);
  }
}

const body = `// AUTO-GENERATED by scripts/gen-post-locales.mjs — do not edit by hand.
// Which locales actually publish each blog slug. Consumed by the language
// switcher (a client component) so it never links to an untranslated post.
import type { Locale } from "@/lib/i18n";

export const postLocales: Readonly<Record<string, Locale[]>> = ${JSON.stringify(
  bySlug,
  null,
  2,
)};
`;

fs.writeFileSync(OUT, body, "utf8");
console.log(`post-locales: ${Object.keys(bySlug).length} slugs written`);
